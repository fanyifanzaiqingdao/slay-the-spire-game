const cardsPath = path.join(root, 'src/data/japanese/cards.json')
const enemiesPath = path.join(root, 'src/data/japanese/enemies.json')

const existingCards = JSON.parse(fs.readFileSync(cardsPath, 'utf8'))
const actIds = new Set(act1Cards.map(c => c.id))
const stripped = existingCards.filter(c => !actIds.has(c.id))
const mergedCards = [...stripped, ...act1Cards]
fs.writeFileSync(cardsPath, JSON.stringify(mergedCards, null, 2) + '\n')
console.log('cards:', mergedCards.length)

const existingEnemies = JSON.parse(fs.readFileSync(enemiesPath, 'utf8'))
